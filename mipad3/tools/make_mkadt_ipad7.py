#!/usr/bin/env python3
"""Derive tools/mkadt_ipad7.py from upstream tools/mkadt.py (upstream stays untouched).

Only the IDENTITY layer is switched from iPhone X (D22AP) to iPad 7 Wi-Fi (J171AP, iPad7,11).
The SoC layer (cpus, arm-io, ufs, GIC addresses) is still Snapdragon and must be ported to
MT8176 separately. Every replacement is asserted so upstream changes fail loudly.

    python3 mipad3/tools/make_mkadt_ipad7.py
"""
import os

root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
src = os.path.join(root, "tools", "mkadt.py")
dst = os.path.join(root, "tools", "mkadt_ipad7.py")
text = open(src).read()

REPL = [
    ("../research/ipsw-x/d22ap.adt", "../research/ipsw-ipad7/j171ap.adt"),
    ("('display-scale', u32(3)),", "('display-scale', u32(2)),"),
    ("cstr('D22AP') + cstr('iPhone10,3') + cstr('xiaomi,sweet') + cstr('qcom,sm7150') + cstr('AppleARM')",
     "cstr('J171AP') + cstr('iPad7,11') + cstr('xiaomi,sweet') + cstr('qcom,sm7150') + cstr('AppleARM')"),
    ("('model', cstr('iPhone10,3')),", "('model', cstr('iPad7,11')),"),
    ("('target-type', cstr('D22')),", "('target-type', cstr('J171')),"),
    ("('target-sub-type', cstr('D22AP')),", "('target-sub-type', cstr('J171AP')),"),
]
for old, new in REPL:
    n = text.count(old)
    assert n == 1, "expected exactly one match for %r, found %d" % (old, n)
    text = text.replace(old, new)

header = '''# GENERATED by mipad3/tools/make_mkadt_ipad7.py from tools/mkadt.py - do not edit, regenerate.
# Identity = iPad 7 Wi-Fi (J171AP, iPad7,11). Needs research/ipsw-ipad7/j171ap.adt
# (python3 mipad3/tools/fetch_j171ap.py). TODO: SoC nodes are still Snapdragon (MT8176 port).
'''
first, _, rest = text.partition("\n")
if first.startswith("#!"):
    text = first + "\n" + header + rest
else:
    text = header + text
open(dst, "w").write(text)
print("wrote", dst)
